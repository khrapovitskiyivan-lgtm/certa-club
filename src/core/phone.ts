// Форматирование телефона при вводе: российские номера по маске +7 (XXX) XXX-XX-XX,
// остальные страны свободно, с плюсом и цифрами.
export function formatPhone(input: string): string {
  const intl = input.trim().startsWith("+");
  let d = input.replace(/\D/g, "");
  if (!d) return intl ? "+" : "";
  if (!intl && (d[0] === "8" || d[0] === "7")) d = "7" + d.slice(1);
  else if (!intl && d[0] === "9") d = "7" + d;
  if (d[0] !== "7") return "+" + d.slice(0, 15);

  const n = d.slice(1, 11);
  let out = "+7";
  if (n.length > 0) out += " (" + n.slice(0, 3);
  if (n.length >= 3) out += ")";
  if (n.length > 3) out += " " + n.slice(3, 6);
  if (n.length > 6) out += "-" + n.slice(6, 8);
  if (n.length > 8) out += "-" + n.slice(8, 10);
  return out;
}

// Полный ли номер: российский из 11 цифр, иностранный от 8 до 15 цифр.
export function isCompletePhone(value: string): boolean {
  const d = value.replace(/\D/g, "");
  return d[0] === "7" ? d.length === 11 : d.length >= 8 && d.length <= 15;
}

